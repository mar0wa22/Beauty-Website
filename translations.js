/* =====================================================
   CURRENT LANGUAGE
===================================================== */

let currentLanguage =
    localStorage.getItem("femoraLanguage") || "en";


/* =====================================================
   APPLY TRANSLATIONS
===================================================== */

function applyTranslations() {

    const language =
        translations[currentLanguage];


    /* =================================================
       CHANGE TEXT CONTENT
    ================================================= */

    document.querySelectorAll(
        "[data-i18n]"
    ).forEach(element => {


        const key =
            element.getAttribute("data-i18n");


        if (language[key]) {

            element.textContent =
                language[key];

        }

    });


    /* =================================================
       CHANGE PLACEHOLDERS
    ================================================= */

    document.querySelectorAll(
        "[data-i18n-placeholder]"
    ).forEach(element => {


        const key =
            element.getAttribute(
                "data-i18n-placeholder"
            );


        if (language[key]) {

            element.placeholder =
                language[key];

        }

    });


    /* =================================================
       CHANGE TITLE
    ================================================= */

    document.querySelectorAll(
        "[data-i18n-title]"
    ).forEach(element => {


        const key =
            element.getAttribute(
                "data-i18n-title"
            );


        if (language[key]) {

            element.title =
                language[key];

        }

    });


    /* =================================================
       DOCUMENT LANGUAGE + DIRECTION
    ================================================= */

    if (currentLanguage === "ar") {

        document.documentElement.lang = "ar";

        document.documentElement.dir = "rtl";

        document.body.classList.add(
            "rtl"
        );

    }

    else {

        document.documentElement.lang = "en";

        document.documentElement.dir = "ltr";

        document.body.classList.remove(
            "rtl"
        );

    }


    /* =================================================
       UPDATE LANGUAGE BUTTON
    ================================================= */

    updateLanguageButton();


    /* =================================================
       UPDATE PAGE DYNAMIC CONTENT
    ================================================= */

    updateDynamicTranslations();

}


/* =====================================================
   UPDATE LANGUAGE BUTTON
===================================================== */

function updateLanguageButton() {

    const button =
        document.getElementById(
            "language-toggle"
        );


    if (!button) {

        return;

    }


    if (currentLanguage === "en") {

        button.textContent = "AR";

    }

    else {

        button.textContent = "EN";

    }

}


/* =====================================================
   TOGGLE LANGUAGE
===================================================== */

function toggleLanguage() {

    if (currentLanguage === "en") {

        currentLanguage = "ar";

    }

    else {

        currentLanguage = "en";

    }


    localStorage.setItem(
        "femoraLanguage",
        currentLanguage
    );


    applyTranslations();


    /*
       Reload dynamic pages
       so JavaScript-generated content
       is translated correctly.
    */

    refreshDynamicPage();

}


/* =====================================================
   REFRESH DYNAMIC PAGE CONTENT
===================================================== */

function refreshDynamicPage() {


    /* PRODUCTS PAGE */

    if (
        typeof displayProducts === "function"
    ) {

        displayProducts();

    }


    /* FAVORITES PAGE */

    if (
        typeof displayFavorites === "function"
    ) {

        displayFavorites();

    }


    /* CART PAGE */

    if (
        typeof displayCart === "function"
    ) {

        displayCart();

    }

}


/* =====================================================
   GET TRANSLATION
===================================================== */

function t(key) {

    if (
        translations[currentLanguage] &&
        translations[currentLanguage][key]
    ) {

        return translations[currentLanguage][key];

    }


    return key;

}


/* =====================================================
   TRANSLATE DYNAMIC CONTENT
===================================================== */

function updateDynamicTranslations() {


    /* CART PAGE */

    const cartHeader =
        document.querySelector(".cart-header span");

    if (cartHeader) {

        cartHeader.textContent =
            t("cartBadge");

    }


    /* CHECKOUT */

    const checkoutTitle =
        document.querySelector(
            ".checkout-header h2"
        );

    if (checkoutTitle) {

        checkoutTitle.textContent =
            t("secureCheckout");

    }


    const checkoutDescription =
        document.querySelector(
            ".checkout-header p"
        );

    if (checkoutDescription) {

        checkoutDescription.textContent =
            t("checkoutDescription");

    }

}


